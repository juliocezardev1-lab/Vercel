-- Additive authentication schema; safe to apply without altering product records.
CREATE TABLE IF NOT EXISTS public.auth_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'user')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT auth_users_identifier_format CHECK (
        identifier = lower(btrim(identifier))
        AND length(identifier) BETWEEN 3 AND 100
    )
);

CREATE TABLE IF NOT EXISTS public.auth_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.auth_users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT auth_sessions_token_hash_format CHECK (token_hash ~ '^[a-f0-9]{64}$')
);

CREATE INDEX IF NOT EXISTS auth_sessions_expiration_idx
    ON public.auth_sessions (expires_at);

CREATE TABLE IF NOT EXISTS public.login_attempts (
    bucket_hash TEXT PRIMARY KEY,
    window_started_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL CHECK (attempts > 0),
    blocked_until TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS login_attempts_window_started_at_idx
    ON public.login_attempts (window_started_at);
